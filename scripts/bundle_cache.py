#!/usr/bin/env python3
"""Bundle every rendered cache set into apps/web/cache-data.js.

Each frame PNG becomes a data URI inside window.SKYBLINK_CACHE, so the
deployed site is a handful of flat text files (easy GitHub Pages upload,
works from file://, zero backend). The fetch-based path stays as fallback.
"""
import base64
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WEB = os.path.join(ROOT, "apps", "web")
CACHE = os.path.join(WEB, "cache")


def main():
    bundle = {}
    for slug in sorted(os.listdir(CACHE)):
        d = os.path.join(CACHE, slug)
        man_path = os.path.join(d, "manifest.json")
        if not os.path.isdir(d) or not os.path.exists(man_path):
            continue
        with open(man_path) as f:
            manifest = json.load(f)
        enrich_path = os.path.join(d, "enrich.json")
        if os.path.exists(enrich_path):
            with open(enrich_path) as f:
                enrich = json.load(f)
            by_obs = {e["obs_id"]: e for e in enrich.get("frames", [])}
            for fr in manifest["frames"]:
                e = by_obs.get(fr["obs_id"])
                if e:
                    fr["clean_pct"] = e.get("clean_pct")
                    fr["band_flux"] = e.get("band_flux")
                    fr["wave_um"] = e.get("wave_um")
            manifest["gaia"] = enrich.get("gaia", [])
        spec_path = os.path.join(d, "spectrum.json")
        if os.path.exists(spec_path):
            with open(spec_path) as f:
                manifest["spectrum"] = json.load(f)
        frames = {}
        for fr in manifest["frames"]:
            with open(os.path.join(d, fr["png"]), "rb") as f:
                frames[fr["png"]] = "data:image/png;base64," + \
                    base64.b64encode(f.read()).decode()
        bundle[slug] = {"manifest": manifest, "frames": frames}
    out = os.path.join(WEB, "cache-data.js")
    with open(out, "w") as f:
        f.write("/* Generated by scripts/bundle_cache.py - real SPHEREx frames, base64. */\n")
        f.write("window.SKYBLINK_CACHE = ")
        json.dump(bundle, f)
        f.write(";\n")
    print(f"bundled {len(bundle)} sets -> {out} ({os.path.getsize(out)//1024} KB)")


if __name__ == "__main__":
    main()
